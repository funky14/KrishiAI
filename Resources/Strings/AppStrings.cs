    public static string GetString(string key)
    {
        var currentLanguage = CultureInfo.CurrentUICulture.Name;

        if (_translations.TryGetValue(key, out var translations))
        {
            if (translations.TryGetValue(currentLanguage, out var translation))
            {
                return translation;
            }
            // Fallback to English
            if (translations.TryGetValue("en-US", out var fallback))
            {
                return fallback;
            }
        }

        return key; // Return key if translation not found
    }

    // Allow runtime registration of additional translation keys (used by startup code)
    public static void RegisterTranslations(Dictionary<string, Dictionary<string, string>> additions)
    {
        if (additions == null) return;

        foreach (var kv in additions)
        {
            // overwrite or add
            _translations[kv.Key] = kv.Value;
        }
    }

